void main(void) {
  byte hx = 128;
  byte hy = 128;

  exidy_init();
  load_charset((const byte*)FONT8X8, sizeof(FONT8X8));
  clrscr(' ');
  put_string(8, 4, "HELLO EXIDY!");
  put_string(6, 6, "ARROWS MOVE");
  put_string(6, 8, "SPACE = FIRE");

  while (1) {
    wait_vblank();

    if (LEFT1 && hx < 250) hx += 2;
    if (RIGHT1 && hx > 5) hx -= 2;
    if (UP1 && hy < 250) hy += 2;
    if (DOWN1 && hy > 5) hy -= 2;

    set_sprite(0, 0, hx, hy);
    set_sprite(1, 0, (byte)(0 - hx), hy);

    put_string(2, 20, "FRAME ");
    {
      static const char HEX[] = "0123456789ABCDEF";
      poke_tile(8, 20, HEX[video_framecount >> 4]);
      poke_tile(9, 20, HEX[video_framecount & 15]);
    }
    put_string(2, 22, FIRE1 ? "FIRE ON " : "FIRE OFF");
  }
}
