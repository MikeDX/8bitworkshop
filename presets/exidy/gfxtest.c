void main(void) {
  word i;

  exidy_init();
  load_charset((const byte*)FONT8X8, sizeof(FONT8X8));

  /* Fill screen with all 256 tiles (32×32). */
  for (i = 0; i < SCREEN_W * SCREEN_H; i++) {
    SCREEN_RAM[i] = (byte)i;
  }

  put_string(0, 30, "EXIDY GFXTEST");

  while (1) {
    wait_vblank();
    set_sprite(0, 0, (byte)(0 - video_framecount), 16);
    set_sprite(1, 0, video_framecount, 16);

    /* Cycle background color latch a bit for flair. */
    if ((video_framecount & 0x3f) == 0) {
      set_palette(
        (byte)(0b10111100 ^ video_framecount),
        (byte)(0b11111010 ^ (video_framecount >> 1)),
        (byte)(0b01000001 ^ (video_framecount >> 2))
      );
    }
  }
}
