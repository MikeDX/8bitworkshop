void main(void) {
  byte x, y, i;
  byte t = 0;

  mcr_init();

  for (i = 0; i < 16; i++)
    set_color(i, (i & 1) ? 7 : 0, (i & 2) ? 7 : 2, (i & 4) ? 7 : 0);
  set_color(16, 0, 0, 0);
  set_color(17, 7, 7, 0);
  set_color(18, 0, 7, 7);
  set_color(19, 7, 0, 7);
  set_color(20, 7, 7, 7);
  set_color(21, 7, 3, 0);
  set_color(22, 3, 7, 3);
  set_color(23, 3, 3, 7);

  memset(vram, 0, 0x800);
  for (y = 0; y < TILE_ROWS; y++) {
    for (x = 0; x < TILE_COLS; x++) {
      byte code = (byte)(1 + ((x + y) & 3));
      if (code > 3) code = 1;
      set_tile(x, y, code, (byte)((x >> 3) & 3), 0, 0);
    }
  }

  while (1) {
    wait_vblank();
    t++;
    for (i = 0; i < 8; i++) {
      word sx = (word)(40 + i * 48);
      word sy = (word)(60 + ((t + i * 16) & 63));
      set_sprite_xy(i, (byte)(i & 1), (byte)(i & 3), sx, sy);
    }
  }
}
