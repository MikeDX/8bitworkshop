void main(void) {
  byte x, y;
  word sx = 80;
  word sy = 120;
  sbyte dx = 2;
  sbyte dy = 2;

  mcr_init();
  (void)bg_gfx[0];
  (void)spr_gfx[0];

  set_color(0, 0, 0, 0);
  set_color(1, 0, 0, 7);
  set_color(2, 7, 7, 7);
  set_color(3, 7, 7, 0);
  set_color(16, 0, 0, 0);
  set_color(17, 7, 7, 0);
  set_color(18, 7, 0, 0);
  set_color(19, 0, 7, 0);

  memset(vram, 0, 0x800);
  for (y = 0; y < TILE_ROWS; y++) {
    for (x = 0; x < TILE_COLS; x++) {
      if (x == 0 || y == 0 || x == TILE_COLS - 1 || y == TILE_ROWS - 1)
        set_tile(x, y, 1, 0, 0, 0);
      else
        set_tile(x, y, 0, 0, 0, 0);
    }
  }

  while (1) {
    wait_vblank();
    sx += dx;
    sy += dy;
    if (sx < 8 || sx > 480) dx = (sbyte)-dx;
    if (sy < 8 || sy > 440) dy = (sbyte)-dy;
    set_sprite_xy(0, 0, 0, sx, sy);
  }
}
