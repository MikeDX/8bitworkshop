void count_dots(void) {
  /* Fixed arcade maze — skip recounting via maze_src. */
  dots_left = NUM_DOTS;
  dots_eaten = 0;
  elroy = 0;
}

byte maze_tile(byte tx, byte ty) {
  return peek_tile(tx, ty);
}

/* Mid-band VRAM (screen y=2..33): strip (27-tx) × 32 + (ty-2).
 * Use an explicit word offset — SDCC miscompiles the pointer form of
 * `((word)(27-tx)<<5)` as a byte rotate (wrong for strip ≥ 8). */
byte peek_maze(byte tx, byte ty) {
  word off = ((word)(27 - tx) << 5) + (byte)(ty - 2);
  return VRAM_MID[off];
}

void poke_maze(byte tx, byte ty, byte tile, byte pal) {
  word off = ((word)(27 - tx) << 5) + (byte)(ty - 2);
  VRAM_MID[off] = tile;
  CRAM_MID[off] = pal;
}

byte tile_blocked(byte tx, byte ty) {
  if (tx >= 28 || ty >= 36) return 1;
  if (ty >= 2 && ty < 34)
    return peek_maze(tx, ty) >= 0xC0;
  return peek_tile(tx, ty) >= 0xC0;
}

/* Table A.1 — fright seconds (×60 at use). 0 = no blue. */
static const byte fright_secs[21] = {
  6, 5, 4, 3, 2, 5, 2, 2,
  1, 5, 2, 1, 1, 3, 1, 1,
  0, 1, 0, 0, 0
};
/* Table A.1 — warning flash count; flash window = count×28 frames. */
static const byte fright_flashes[21] = {
  5, 5, 5, 5, 5, 5, 5, 5,
  3, 5, 5, 3, 3, 5, 3, 3,
  0, 3, 0, 0, 0
};

word fright_duration(void) {
  byte lv = level;
  byte s;
  if (lv > 20) lv = 20;
  s = fright_secs[lv];
  /* s*60 = (s<<6)-(s<<2) */
  return (word)(((word)s << 6) - ((word)s << 2));
}

word fright_flash_ticks(void) {
  byte lv = level;
  byte n;
  if (lv > 20) lv = 20;
  n = fright_flashes[lv];
  /* n*28 = (n<<5)-(n<<2) */
  return (word)(((word)n << 5) - ((word)n << 2));
}

void try_eat_tile(byte tx, byte ty) {
  byte t;
  byte is_dot;
  if (tx >= 28 || ty >= 36) return;
  t = peek_maze(tx, ty);
  if (t != T_DOT_A && t != T_POWER_A) return;
  is_dot = (byte)(t == T_DOT_A);

  poke_maze(tx, ty, T_BLANK_A, 0);
  if (dots_left) dots_left--;
  dots_eaten++;
  /* Dossier: only regular dots reset force-exit / feed house counters.
   * Energizers do not. */
  if (is_dot)
    force_house = 0;

  if (t == T_POWER_A) {
    byte i;
    play_sfx(6);
    power_ticks = fright_duration(); /* [CHANGE] full A.1; may be 0 */
    eat_combo = 0;
    if (!attract_demo) score += 5;
    pac_stop = 3; /* [CONFIRM] dossier: 3-frame pause on energizer */
    /* [CONFIRM] fright on ALL ghosts; reverse maze ghosts (even if duration 0) */
    for (i = 0; i < GHOST_N; i++) {
      byte m = ghosts[i].mode;
      if (power_ticks)
        ghosts[i].frightened = 1;
      if (m == MODE_SCATTER || m == MODE_CHASE || m == MODE_FRIGHT) {
        ghosts[i].next_dir = opposite_dir(ghosts[i].dir);
        if (power_ticks) ghosts[i].mode = MODE_FRIGHT;
      }
    }
  } else {
    waka ^= 1;
    play_sfx(waka ? 1 : 2);
    if (!attract_demo) score += 1;
    pac_stop = 1; /* [CONFIRM] dossier: 1-frame pause on dot */
  }

  if (dots_eaten == 70 || dots_eaten == 170)
    /* [CONFIRM] fruit at 70 and 170 dots; [CHANGE] stays 9–10s */
    fruit_visible = (word)(540 + (rand8() & 63));

  update_elroy();

  /* House / global counters: regular dots only (dossier §ghost house). */
  if (!is_dot) return;

  if (global_dot_mode) {
    /* [CONFIRM] after death, global counter; Clyde@32 deactivates it */
    global_dot_counter++;
  } else {
    /* [CONFIRM] one personal counter: first of Pinky→Inky→Clyde still in house */
    byte i;
    for (i = 1; i <= 3; i++) {
      if (ghosts[i].mode != MODE_HOUSE) continue;
      ghosts[i].dot_counter++;
      break;
    }
  }
}
