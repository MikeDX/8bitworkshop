/* Bits for tiles 0xc0..0xe7: set = same index on L/R (flip-symmetric). */
static const byte maze_sym[5] = { 0x00, 0x80, 0x00, 0xb8, 0x20 };

/* Playfield tile cache — 28×31 = 868 bytes (collision + eat without VRAM). */
static byte maze_ram[MAZE_ROWS * 28];

static byte mirror_tile(byte t) {
  byte ix;
  if (t < 0xc0) return t; /* dots, power, blank */
  ix = (byte)(t - 0xc0);
  if (ix < 40 && (maze_sym[ix >> 3] & (byte)(1 << (ix & 7))))
    return t;
  return (byte)(t ^ 1);
}

/*
 * Fill maze_ram + BAC06.
 *
 * VRAM is linear in hx at fixed hy: addr = 0x0800 + (hy*32 + hx)*2.
 * After rotate, a portrait column (fixed tx → fixed hy) is one contiguous
 * strip (hx decreases as ty increases → walk addr downward by 2).
 * Source is row-major left-half; we gather by column for the VRAM walk.
 */
void draw_maze(void) {
  byte col, row;
  byte* ram;

  /* 1) Expand left half + mirror into maze_ram (row-major). */
  {
    const byte* src = maze_left;
    for (row = 0; row < MAZE_ROWS; row++) {
      ram = &maze_ram[(word)row * 28u];
      for (col = 0; col < MAZE_HALF; col++) {
        byte tile = *src++;
        ram[col] = tile;
        ram[27 - col] = mirror_tile(tile);
      }
    }
  }

  /* 2) One linear VRAM strip per portrait column (hy = tx + 2). */
  for (col = 0; col < 28; col++) {
    byte hy = (byte)(col + LOGIC_X_SHIFT);
    /* ty = MAZE_Y0+0 → hx = 31-(3-2) = 30; each next row hx-- */
    word addr = (word)(0x0800 + ((word)hy * 32u + 30u) * 2u);
    ram = &maze_ram[col]; /* column col, row 0 */
    for (row = 0; row < MAZE_ROWS; row++) {
      byte tile = *ram;
      byte pal = (tile == T_DOOR) ? PAL_DOOR : PAL_MAZE;
      byte hi = (byte)((pal & 0x0f) << 4);
      POKE(addr, hi);
      POKE(addr + 1, tile);
      ram += 28;   /* next maze row, same column */
      addr -= 2;   /* next logical row → hx-- → prior word */
    }
  }
}

void count_dots(void) {
  /* Fixed arcade maze — skip recounting via maze_src. */
  dots_left = NUM_DOTS;
  dots_eaten = 0;
  elroy = 0;
}

byte maze_tile(byte tx, byte ty) {
  return peek_maze(tx, ty);
}

byte peek_maze(byte tx, byte ty) {
  if (tx >= 28 || ty < MAZE_Y0 || ty >= (byte)(MAZE_Y0 + MAZE_ROWS))
    return peek_tile(tx, ty);
  return maze_ram[(word)(ty - MAZE_Y0) * 28u + tx];
}

void poke_maze(byte tx, byte ty, byte tile, byte pal) {
  if (tx < 28 && ty >= MAZE_Y0 && ty < (byte)(MAZE_Y0 + MAZE_ROWS))
    maze_ram[(word)(ty - MAZE_Y0) * 28u + tx] = tile;
  poke_tile(tx, ty, tile, pal);
}

byte tile_blocked(byte tx, byte ty) {
  if (tx >= 28 || ty >= 36) return 1;
  if (ty >= MAZE_Y0 && ty < (byte)(MAZE_Y0 + MAZE_ROWS))
    return (byte)(maze_ram[(word)(ty - MAZE_Y0) * 28u + tx] >= 0xC0);
  return (byte)(peek_tile(tx, ty) >= 0xC0);
}

/* Table A.1 — fright seconds (×60 at use). 0 = no blue. */
static const byte fright_secs[21] = {
  6, 5, 4, 3, 2, 5, 2, 2,
  1, 5, 2, 1, 1, 3, 1, 1,
  0, 1, 0, 0, 0
};
/* Table A.1 — warning flash count; flash window = count×28 frames. */
static const byte fright_flashes[21] = {
  5, 5, 5, 5, 5, 5, 5, 5,
  3, 5, 5, 3, 3, 5, 3, 3,
  0, 3, 0, 0, 0
};

word fright_duration(void) {
  byte lv = level;
  byte s;
  if (lv > 20) lv = 20;
  s = fright_secs[lv];
  /* s*60 = (s<<6)-(s<<2) */
  return (word)(((word)s << 6) - ((word)s << 2));
}

word fright_flash_ticks(void) {
  static byte cached_lv = 0xff;
  static word cached;
  byte lv = level;
  byte n;
  if (lv > 20) lv = 20;
  if (lv == cached_lv) return cached;
  cached_lv = lv;
  n = fright_flashes[lv];
  /* n*28 = (n<<5)-(n<<2) */
  cached = (word)(((word)n << 5) - ((word)n << 2));
  return cached;
}

void try_eat_tile(byte tx, byte ty) {
  byte t;
  byte is_dot;
  if (tx >= 28 || ty >= 36) return;
  t = peek_maze(tx, ty);
  if (t != T_DOT_A && t != T_POWER_A) return;
  is_dot = (byte)(t == T_DOT_A);

  poke_maze(tx, ty, T_BLANK_A, 0);
  if (dots_left) dots_left--;
  dots_eaten++;
  /* Dossier: only regular dots reset force-exit / feed house counters.
   * Energizers do not. */
  if (is_dot)
    force_house = 0;

  if (t == T_POWER_A) {
    byte i;
    play_sfx(6);
    power_ticks = fright_duration(); /* [CHANGE] full A.1; may be 0 */
    eat_combo = 0;
    if (!attract_demo) score += 5;
    pac_stop = 3; /* [CONFIRM] dossier: 3-frame pause on energizer */
    /* [CONFIRM] fright on ALL ghosts; reverse maze ghosts (even if duration 0) */
    for (i = 0; i < GHOST_N; i++) {
      byte m = ghosts[i].mode;
      if (power_ticks)
        ghosts[i].frightened = 1;
      if (m == MODE_SCATTER || m == MODE_CHASE || m == MODE_FRIGHT) {
        ghosts[i].next_dir = opposite_dir(ghosts[i].dir);
        if (power_ticks) ghosts[i].mode = MODE_FRIGHT;
      }
    }
  } else {
    waka ^= 1;
    play_sfx(waka ? 1 : 2);
    if (!attract_demo) score += 1;
    pac_stop = 1; /* [CONFIRM] dossier: 1-frame pause on dot */
  }

  if (dots_eaten == 70 || dots_eaten == 170)
    /* [CONFIRM] fruit at 70 and 170 dots; [CHANGE] stays 9–10s */
    fruit_visible = (word)(540 + (rand8() & 63));

  update_elroy();

  /* House / global counters: regular dots only (dossier §ghost house). */
  if (!is_dot) return;

  if (global_dot_mode) {
    /* [CONFIRM] after death, global counter; Clyde@32 deactivates it */
    global_dot_counter++;
  } else {
    /* [CONFIRM] one personal counter: first of Pinky→Inky→Clyde still in house */
    byte i;
    for (i = 1; i <= 3; i++) {
      if (ghosts[i].mode != MODE_HOUSE) continue;
      ghosts[i].dot_counter++;
      break;
    }
  }
}
