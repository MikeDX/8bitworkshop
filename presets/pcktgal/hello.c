void main(void) {
  static const char line1[] = { 8, 6, 10, 10, 11, 0, 15, 11, 13, 10, 5, 16, 0 };
  static const char line2[] = { 12, 11, 4, 9, 6, 14, 0, 7, 3, 10, 0 };
  unsigned char i;

  INTVEC = nmi_handler;

  /* BAC06: 8x8 mode, bit1 set disables TILE_FLIPX so glyphs match asset data */
  POKE(0x1800, 0x03);
  /* clear scroll */
  POKE(0x1810, 0); POKE(0x1811, 0);
  POKE(0x1812, 0); POKE(0x1813, 0);

  /* hide sprites */
  for (i = 0; i < 64; i++) {
    POKE(0x1000 + i * 4, 0xf8);
  }

  /* checkerboard background */
  {
    unsigned char x, y;
    for (y = 0; y < 28; y++) {
      for (x = 0; x < 32; x++) {
        unsigned char t = ((x ^ y) & 1) ? 2 : 0;
        put_tile(x, y, t, (y < 2) ? 0 : 1);
      }
    }
  }
  (void)TILES; /* keep CHARS segment linked */

  put_str(10, 10, line1, 0);
  put_str(10, 12, line2, 0);

  while (1) {
    /* wait for next frame via NMI */
    char f = framecount;
    while (f == framecount) { }
  }
}
