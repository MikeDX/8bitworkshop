void main(void) {
  static const char title[] = { 12, 11, 4, 9, 6, 14, 0, 7, 3, 10, 0 };
  static const char label[] = { 14, 6, 14, 14, 0 }; /* TEST */
  unsigned char x, y, i;

  INTVEC = nmi_handler;
  POKE(0x1800, 0x03); /* 8x8 + no TILE_FLIPX (homebrew glyphs) */
  set_scroll(0, 0);

  for (i = 0; i < 64; i++)
    hide_sprite(i);

  /* Playfield: solid left column marker + grid. Only 32 columns are CPU-mapped;
     scrolling X past 256 shows blank in MAME (and now in our emu). */
  for (y = 0; y < 32; y++) {
    for (x = 0; x < 32; x++) {
      unsigned char t = 0;
      if (x == 0) t = 1;
      else if ((x & 3) == 0 || (y & 3) == 0) t = 2;
      put_tile(x, y, t, (t == 1) ? 0 : 1);
    }
  }
  put_str(8, 1, title, 0);
  put_str(12, 3, label, 0);
  (void)TILES;
  (void)SPRITE_GFX;
  (void)COLOR_PROMS;

  while (1) {
    unsigned char f = framecount;
    unsigned char bounce;
    unsigned int sx;

    /* Ping-pong X scroll 0..400 — past 256 the PF goes blank (no 256 wrap) */
    {
      unsigned int cycle = ((unsigned int)f * 2u) % 800u;
      sx = (cycle < 400u) ? cycle : (800u - cycle);
    }
    set_scroll(sx, 0);

    bounce = (f >> 1) & 0x3f;
    if (bounce >= 32) bounce = 63 - bounce;

    /* Colour bank strip (static) */
    for (i = 0; i < 8; i++)
      set_sprite(i, (unsigned char)(16 + i * 28), 48, 3, i, 0);

    /* Flip probe: arrow facing right / flipx / flipy / both */
    set_sprite(8, 40, 90, 2, 2, 0);
    set_sprite(9, 80, 90, 2, 2, 4);   /* flipx */
    set_sprite(10, 120, 90, 2, 2, 2);  /* flipy */
    set_sprite(11, 160, 90, 2, 2, 6);  /* both */

    /* Movers: ball + smile, including off left/right edges */
    set_sprite(12, (unsigned char)(f), 130, 0, 0, 0);
    set_sprite(13, (unsigned char)(240 - f), 150, 1, 1, 0);
    set_sprite(14, 200, (unsigned char)(40 + bounce), 0, 3, 0);
    set_sprite(15, 24, (unsigned char)(180 - bounce), 1, 4, 4);

    while (f == framecount) { }
  }
}
