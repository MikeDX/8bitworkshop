#include <peekpoke.h>

volatile char framecount;

void nmi_handler(void) {
  asm("inc _framecount");
  asm("rti");
}

extern void (*INTVEC)(void);
#pragma zpsym("INTVEC")

void put_tile(unsigned char x, unsigned char y, unsigned int tile, unsigned char color) {
  unsigned int addr = 0x0800 + ((y * 32u + x) * 2u);
  unsigned int word = ((unsigned int)color << 12) | (tile & 0xfff);
  POKE(addr, word >> 8);
  POKE(addr + 1, word & 0xff);
}

void put_str(unsigned char x, unsigned char y, const char* tiles, unsigned char color) {
  while (*tiles) {
    put_tile(x++, y, (unsigned char)*tiles++, color);
  }
}

void hide_sprite(unsigned char i) {
  POKE(0x1000 + i * 4u, 0xf8);
}

/* x,y are top-left on the 256×240 virtual screen (MAME: sx=240-x, sy=240-y) */
void set_sprite(unsigned char i, unsigned char x, unsigned char y,
                unsigned int code, unsigned char color, unsigned char flip) {
  unsigned int a = 0x1000 + i * 4u;
  POKE(a + 0, 240 - y);
  POKE(a + 1, ((color & 7) << 4) | (flip & 6) | ((code >> 8) & 1));
  POKE(a + 2, 240 - x);
  POKE(a + 3, code & 0xff);
}

void set_scroll(unsigned int x, unsigned int y) {
  POKE(0x1810, x >> 8); POKE(0x1811, x & 0xff);
  POKE(0x1812, y >> 8); POKE(0x1813, y & 0xff);
}

